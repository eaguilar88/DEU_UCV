CREATE TYPE "provider_type" AS ENUM (
  'user',
  'extension_group'
);

CREATE TYPE "education_level" AS ENUM (
  'bachiller',
  'universitaria_incompleta',
  'universitaria_completa',
  'posgrado'
);

CREATE TYPE "request_status" AS ENUM (
  'created',
  'under_review',
  'rejected',
  'approved'
);

CREATE TYPE "contact_type" AS ENUM (
  'user',
  'course',
  'extension_group'
);

CREATE TYPE "course_participant_status" AS ENUM (
  'abandoned',
  'approved',
  'failed'
);

CREATE TYPE "user_role" AS ENUM (
  'root', 
  'admin', 
  'facilitador', 
  'estudiante', 
  'extensión'
);

CREATE TABLE "deu"."users" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY NOT NULL,
  "ci" integer UNIQUE NOT NULL,
  "username" varchar UNIQUE NOT NULL,
  "first_name" varchar NOT NULL,
  "last_name" varchar NOT NULL,
  "date_of_birth" date,
  "gender" varchar,
  "education" education_level NOT NULL,
  "address" varchar,
  "created_at" timestamp DEFAULT (now()),
  "updated_at" timestamp DEFAULT (now()),
  "password" char(60) NOT NULL
);

CREATE TABLE "deu"."providers" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY NOT NULL,
  "entity_id" integer NOT NULL,
  "entity_type" provider_type NOT NULL,
  "registration_date" date,
  "code" varchar,
  "created_at" timestamp DEFAULT (now()),
  "updated_at" timestamp DEFAULT (now())
);

CREATE TABLE "deu"."extension_group" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY NOT NULL,
  "name" varchar,
  "description" text,
  "objective" text,
  "action" text,
  "reach" text,
  "path" varchar
);

CREATE TABLE "deu"."endorsement_requests" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY NOT NULL,
  "user_id" INTEGER REFERENCES deu.users(id) ON DELETE CASCADE,
  "status" request_status,
  "path" varchar,
  "created_at" timestamp DEFAULT (now()),
  "updated_at" timestamp DEFAULT (now())
);

CREATE TABLE "deu"."courses" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY NOT NULL,
  "user_id" INTEGER REFERENCES deu.users(id) ON DELETE CASCADE,
  "endorsement_id" integer,
  "endorsed_by" varchar,
  "objectives" text,
  "content" text,
  "cost" float,
  "location" varchar,
  "created_at" timestamp DEFAULT (now()),
  "updated_at" timestamp DEFAULT (now())
);

CREATE TABLE "deu"."contact_info" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY NOT NULL,
  "entity_id" integer,
  "entity_type" contact_type,
  "email" varchar,
  "phone" varchar
);

CREATE TABLE "deu"."course_cycles" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY NOT NULL,
  "course_id" integer,
  "start_date" date,
  "end_date" date,
  "inscription_date" date,
  "created_at" timestamp DEFAULT (now()),
  "updated_at" timestamp DEFAULT (now())
);

CREATE TABLE "deu"."course_participants" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY NOT NULL,
  "user_id" INTEGER REFERENCES deu.users(id) ON DELETE CASCADE,
  "course_cycle_id" integer,
  "participant_status" course_participant_status,
  "created_at" timestamp DEFAULT (now()),
  "updated_at" timestamp DEFAULT (now())
);

CREATE TABLE "deu"."roles" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY NOT NULL,
  "name" varchar UNIQUE,
  "description" text,
  "created_at" timestamp DEFAULT (now()),
  "updated_at" timestamp DEFAULT (now())
);

CREATE TABLE "deu"."activities" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY NOT NULL,
  "name" varchar,
  "description" text,
  "date" date,
  "path" varchar,
  "location" varchar,
  "assistants" integer
);

CREATE TABLE deu.user_roles (
    user_id INTEGER REFERENCES deu.users(id) ON DELETE CASCADE,
    role_id INTEGER REFERENCES deu.roles(id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, role_id)
);


