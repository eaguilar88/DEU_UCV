COMMENT ON COLUMN contacts.contact_value IS 'El valor real del contacto (por ejemplo, una dirección de correo electrónico o un número de teléfono)';

COMMENT ON COLUMN contacts.owner_type IS 'El tipo de entidad que posee el contacto (''user'' o ''provider'')';

COMMENT ON COLUMN contacts.owner_id IS 'El ID del usuario o proveedor que posee el contacto';

COMMENT ON COLUMN contacts.created_at IS 'Marca de tiempo de cuando se creó la entrada de contacto';

