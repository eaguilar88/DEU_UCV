CREATE TYPE "education_level_enum" AS ENUM (
  'bachiller',
  'universitaria_incompleta',
  'universitaria_completa',
  'posgrado'
);

-- Definir tablas

-- Tabla para almacenar información de usuarios
CREATE TABLE "deu"."users" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY NOT NULL,
  "ci" INTEGER UNIQUE NOT NULL,
  "username" VARCHAR UNIQUE NOT NULL,
  "first_name" VARCHAR NOT NULL,
  "last_name" VARCHAR NOT NULL,
  "date_of_birth" DATE,
  "gender" VARCHAR,
  "education" education_level_enum NOT NULL,
  "address" VARCHAR,
  "created_at" TIMESTAMP DEFAULT (now()),
  "updated_at" TIMESTAMP DEFAULT (now()),
  "password" CHAR(60) NOT NULL
);

-- Tabla para almacenar información de roles
CREATE TABLE "deu"."roles" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY NOT NULL,
  "name" VARCHAR UNIQUE NOT NULL,
  "description" TEXT,
  "created_at" TIMESTAMP DEFAULT (now()),
  "updated_at" TIMESTAMP DEFAULT (now())
);

-- Tabla para almacenar relaciones usuario-rol
CREATE TABLE "deu"."user_roles" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY NOT NULL,
  "user_id" INTEGER NOT NULL REFERENCES deu.users(id) ON DELETE CASCADE,
  "role_id" INTEGER NOT NULL REFERENCES deu.roles(id) ON DELETE CASCADE,
  UNIQUE ("user_id", "role_id")
);

CREATE TYPE "request_status_enum" AS ENUM (
  'created',
  'under_review',
  'rejected',
  'approved'
);

-- Tabla para almacenar información de solicitudes de aval
CREATE TABLE "deu"."requests" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY NOT NULL,
  "user_id" INTEGER NOT NULL REFERENCES deu.users(id) ON DELETE CASCADE,
  "type" entity_type_enum NOT NULL,
  "name" VARCHAR,
  "description" TEXT,
  "status" request_status_enum DEFAULT 'created' NOT NULL,
  "comments" TEXT,
  "created_at" TIMESTAMP DEFAULT (now()),
  "updated_at" TIMESTAMP DEFAULT (now())
);

-- Tabla para almacenar información de documentos de solicitudes
CREATE TABLE "deu"."request_documents" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY NOT NULL,
  "request_id" INTEGER NOT NULL REFERENCES deu.requests(id) ON DELETE CASCADE,
  "path" VARCHAR,
  "created_at" TIMESTAMP DEFAULT (now()),
  "updated_at" TIMESTAMP DEFAULT (now())
);

CREATE TYPE "entity_type_enum" AS ENUM (
  'course',
  'extension_group'
);

-- Tabla para almacenar información de entidades
CREATE TABLE "deu"."entities" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY NOT NULL,
  "name" VARCHAR,
  "description" TEXT,
  "user_id" INTEGER NOT NULL REFERENCES deu.users(id) ON DELETE CASCADE, -- ID del usuario que creó esta entidad de solicitud
  "endorsement_id" INTEGER REFERENCES deu.requests(id) ON DELETE SET NULL, -- ID de la solicitud utilizada para el aval
  "endorsed_by" VARCHAR REFERENCES deu.users(id) ON DELETE SET NULL, -- ID de la cuenta de administrador que aprobó la solicitud
  "created_at" TIMESTAMP DEFAULT (now()),
  "updated_at" TIMESTAMP DEFAULT (now())
);

-- Tabla para almacenar información de grupos de extensión
CREATE TABLE "deu"."extension_groups" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY NOT NULL,
  "entity_id" INTEGER NOT NULL REFERENCES deu.entities(id) ON DELETE SET NULL,
  "name" VARCHAR,
  "description" TEXT,
  "objective" TEXT,
  "action" TEXT,
  "reach" TEXT,
  "path" VARCHAR
);

-- Tabla para almacenar información de cursos
CREATE TABLE "deu"."courses" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY NOT NULL,
  "entity_id" INTEGER NOT NULL REFERENCES deu.entities(id) ON DELETE SET NULL,
  "objectives" TEXT,
  "content" TEXT,
  "cost" FLOAT,
  "location" VARCHAR,
  "created_at" TIMESTAMP DEFAULT (now()),
  "updated_at" TIMESTAMP DEFAULT (now())
);

-- Tabla para almacenar información de ciclos de cursos
CREATE TABLE "deu"."course_cycles" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY NOT NULL,
  "course_id" INTEGER NOT NULL REFERENCES deu.courses(id),
  "start_date" DATE,
  "end_date" DATE,
  "inscription_date" DATE,
  "created_at" TIMESTAMP DEFAULT (now()),
  "updated_at" TIMESTAMP DEFAULT (now())
);

CREATE TYPE "course_participant_status_enum" AS ENUM (
  'abandoned',
  'approved',
  'failed'
);

-- Tabla para almacenar información de participantes de cursos
CREATE TABLE "deu"."course_participants" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY NOT NULL,
  "user_id" INTEGER NOT NULL REFERENCES deu.users(id) ON DELETE CASCADE,
  "course_cycle_id" INTEGER NOT NULL REFERENCES deu.course_cycles(id),
  "participant_status" course_participant_status_enum,
  "created_at" TIMESTAMP DEFAULT (now()),
  "updated_at" TIMESTAMP DEFAULT (now()),
  UNIQUE ("user_id", "course_cycle_id")
);

-- Tabla para almacenar información de actividades
CREATE TABLE "deu"."activities" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY NOT NULL,
  "name" VARCHAR,
  "group_id" INTEGER REFERENCES deu.extension_groups(id) ON DELETE SET NULL,
  "description" TEXT,
  "date" DATE,
  "path" VARCHAR,
  "location" VARCHAR,
  "assistants" INTEGER
);

-- Tabla para almacenar información de proveedores. Un proveedor es aquel que tiene código de proveedor asignado por la DEU.
-- Únicamente los coordinadores de cursos y los representantes de grupos de extensión pueden ser proveedores
CREATE TABLE "deu"."providers" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY NOT NULL,
  "user_id" INTEGER NOT NULL REFERENCES deu.users(id) ON DELETE CASCADE,
  CONSTRAINT "chk_user_role" CHECK (
    EXISTS (
      SELECT 1 
      FROM deu.user_roles ur 
      JOIN deu.roles r ON ur.role_id = r.id 
      WHERE ur.user_id = deu.providers.user_id 
      AND r.name IN ('coordinador', 'grupo')
    )
  ),
  "code" VARCHAR,
  "created_at" TIMESTAMP DEFAULT (now()),
  "updated_at" TIMESTAMP DEFAULT (now())
);

CREATE TYPE "contact_type_enum" AS ENUM (
  'email',
  'phone'
);

CREATE TYPE "owner_type_enum" AS ENUM (
  'user',
  'provider'
);

-- Crear la tabla de contactos con las restricciones y tipos adecuados
-- Tabla para almacenar información de contactos
CREATE TABLE contacts (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY NOT NULL,
    
    -- Tipo de contacto: ya sea 'email' o 'phone'
    contact_type contact_type_enum NOT NULL DEFAULT 'email',
    
    -- El valor real del contacto (por ejemplo, una dirección de correo electrónico o un número de teléfono)
    contact_value TEXT NOT NULL,
    
    -- El tipo de entidad que posee el contacto ('user' o 'provider')
    owner_type owner_type_enum NOT NULL,
    
    -- El ID del usuario o proveedor que posee el contacto
    owner_id BIGINT NOT NULL,
    
    -- Marca de tiempo de cuando se creó la entrada de contacto
    created_at TIMESTAMPTZ DEFAULT NOW(),

    -- Asegura que el mismo valor de contacto no se pueda duplicar para el mismo propietario
    CONSTRAINT unique_contact_per_owner UNIQUE (contact_type, contact_value, owner_type, owner_id),
    
    -- Asegura que owner_id debe existir en la tabla de usuarios o proveedores
    CONSTRAINT fk_user CHECK (
        (owner_type = 'user' AND owner_id IN (SELECT id FROM users))
        OR
        (owner_type = 'provider' AND owner_id IN (SELECT user_id FROM providers))
    )
);

