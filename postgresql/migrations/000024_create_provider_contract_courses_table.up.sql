-- Tabla que registra qué cursos quedaron amparados por cada contrato/adenda
CREATE TABLE
  deu.provider_contract_courses (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY NOT NULL,
    contract_id INTEGER NOT NULL REFERENCES deu.provider_contracts (id) ON DELETE CASCADE,
    course_id INTEGER NOT NULL REFERENCES deu.courses (id) ON DELETE CASCADE,
    created_at TIMESTAMP DEFAULT NOW (),
    UNIQUE (contract_id, course_id)
  );
