-- Tabla para solicitudes de cierre/certificación de ciclos de cursos
CREATE TABLE
  deu.course_cycle_close_requests (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY NOT NULL,
    course_cycle_id INTEGER NOT NULL REFERENCES deu.course_cycles (id) ON DELETE CASCADE,
    submitted_by INTEGER NOT NULL REFERENCES deu.users (id) ON DELETE CASCADE,
    status deu.request_status_enum DEFAULT 'under_review' NOT NULL,
    comments TEXT,
    reviewer_id INTEGER DEFAULT NULL REFERENCES deu.users (id) ON DELETE SET NULL,
    reviewed_at TIMESTAMP DEFAULT NULL,
    created_at TIMESTAMP DEFAULT NOW (),
    updated_at TIMESTAMP DEFAULT NOW (),
    deleted_at TIMESTAMP DEFAULT NULL
  );
