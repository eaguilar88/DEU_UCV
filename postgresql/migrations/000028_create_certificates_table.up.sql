-- Certificados de los participantes aprobados de una cohorte, emitidos al aprobar su cierre
CREATE TABLE
  deu.certificates (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY NOT NULL,
    close_request_id INTEGER NOT NULL REFERENCES deu.course_cycle_close_requests (id) ON DELETE CASCADE,
    course_cycle_id INTEGER NOT NULL REFERENCES deu.course_cycles (id) ON DELETE CASCADE,
    first_name TEXT NOT NULL,
    last_name TEXT NOT NULL,
    document TEXT NOT NULL,
    email TEXT DEFAULT NULL,
    verification_code TEXT NOT NULL UNIQUE,
    storage_key TEXT DEFAULT NULL,
    issued_at TIMESTAMPTZ DEFAULT NULL,
    revoked_at TIMESTAMPTZ DEFAULT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW (),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW (),
    UNIQUE (close_request_id, document)
  );
